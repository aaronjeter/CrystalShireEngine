; Challenge facility records (engine/events/facility.asm), indexed by FACILITY_* (constants/facility_constants.asm).

MACRO facility
; category, parameter (a type or region), level (0: the level cap), style, main prize item (or NO_ITEM; the map gives the prizes), cleared flag (or 0: repeatable)
	db \1, \2, \3, \4
	dw \5, \6
ENDM

MACRO facility_trainers
; FACILITY_ROUNDS trainers: class, id, overworld sprite (shown by the opponent object)
	assert _NARG == FACILITY_ROUNDS * FACILITY_TRAINER_LENGTH
	rept _NARG / FACILITY_TRAINER_LENGTH
		db \1, \2, \3
		shift FACILITY_TRAINER_LENGTH
	endr
ENDM

