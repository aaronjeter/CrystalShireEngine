#!/usr/bin/env python3
"""Generate data/events/vs_seeker_excluded.asm: the map trainers the Vs Seeker
must not ready again.

A map trainer's beaten flag (the first field of its `trainer` header) is
excluded when:
- any .asm outside constants/ uses it other than in its own `trainer` header
  or a `setevent` (a check, a clear, a journal step, a table entry, an
  object_event's visibility flag, ...), or
- the trainer is a Rocket grunt or executive (EXCLUDED_CLASSES).

Usage: vs_seeker_table.py [REPO] [--check]
  --check: exit 1 if the file in the repo is out of date.
"""
import glob
import os
import re
import sys

OUT = 'data/events/vs_seeker_excluded.asm'
EXCLUDED_CLASSES = {'GRUNTM', 'GRUNTF', 'GRUNTS', 'EXECUTIVEM', 'EXECUTIVEF'}

TRAINER_RE = re.compile(r'^\s*trainer\s+(\w+),\s*(\w+),\s*(EVENT_\w+),', re.M)
FLAG_RE = re.compile(r'\bEVENT_BEAT_\w+|\bEVENT_\w+')


def read(path):
    with open(path, 'rb') as f:
        data = f.read()
    try:
        return data.decode('utf-8')
    except UnicodeDecodeError:
        return data.decode('latin-1')


def generate(repo):
    trainers = {}  # flag -> set of classes
    for path in sorted(glob.glob(os.path.join(repo, 'maps', '**', '*.asm'), recursive=True)):
        for m in TRAINER_RE.finditer(read(path)):
            trainers.setdefault(m.group(3), set()).add(m.group(1))

    excluded = {}  # flag -> reason
    for flag, classes in trainers.items():
        bad = classes & EXCLUDED_CLASSES
        if bad:
            excluded[flag] = 'class ' + ', '.join(sorted(bad))

    out_path = os.path.normpath(os.path.join(repo, OUT))
    for path in sorted(glob.glob(os.path.join(repo, '**', '*.asm'), recursive=True)):
        rel = os.path.relpath(path, repo).replace(os.sep, '/')
        if rel.startswith('constants/') or os.path.normpath(path) == out_path:
            continue
        for line in read(path).splitlines():
            code = line.split(';', 1)[0].strip()
            if not code:
                continue
            for m in FLAG_RE.finditer(code):
                flag = m.group(0)
                if flag not in trainers or flag in excluded:
                    continue
                cmd = code.split()[0]
                if cmd in ('trainer', 'setevent'):
                    continue
                excluded[flag] = '%s in %s' % (cmd, rel)

    lines = [
        '; Map trainers the Vs Seeker doesn\'t ready again: their beaten flags,',
        '; ending with -1. Generated by tools/vs_seeker_table.py; don\'t edit.',
        '; %d of %d trainer flags.' % (len(excluded), len(trainers)),
        '',
        'VsSeekerExcludedFlags:',
    ]
    for flag in sorted(excluded):
        lines.append('\tdw %-36s ; %s' % (flag, excluded[flag]))
    lines.append('\tdw -1')
    return '\n'.join(lines) + '\n', len(excluded), len(trainers)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    repo = args[0] if args else '.'
    text, n_ex, n_all = generate(repo)
    path = os.path.join(repo, OUT)
    if '--check' in sys.argv:
        current = read(path) if os.path.exists(path) else ''
        if current != text:
            print('%s is out of date: run tools/vs_seeker_table.py' % OUT)
            sys.exit(1)
        print('%s is up to date (%d of %d trainer flags excluded)' % (OUT, n_ex, n_all))
        return
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d of %d trainer flags excluded' % (OUT, n_ex, n_all))


if __name__ == '__main__':
    main()
