#!/usr/bin/env python3
"""Generate data/wild/nuzlocke_encounter_landmarks.asm: one bit per landmark,
set when some map of that landmark has a wild Pokémon whose catch uses the
Nuzlocke area (the place-name sign shows the area's ball icon only for those).

    python3 tools/nuzlocke_area_table.py [REPO] [--check]

Counted per map: grass and water tables (incl. swarms), a fishing group,
Headbutt/Rock Smash trees (TreeMonMaps), and loadwildmon in its scripts,
except legendaries (always catchable) and forced battles (a loadboss or a
NUZLOCKE_FORCED marker next to the loadwildmon). Maps with LANDMARK_SPECIAL
take their landmark from the outside map at run time, so they can't be
listed: they're reported. --check exits with 1 if the file is out of date.
"""
import os, re, sys

OUT = 'data/wild/nuzlocke_encounter_landmarks.asm'


def read(repo, path):
    with open(os.path.join(repo, path), 'rb') as f:
        data = f.read()
    try:
        return data.decode('utf-8')
    except UnicodeDecodeError:
        return data.decode('latin-1')


def landmarks(repo):
    names = []
    for line in read(repo, 'constants/landmark_constants.asm').splitlines():
        m = re.match(r'\s*const\s+(LANDMARK_\w+)', line)
        if m:
            names.append(m.group(1))
        if re.match(r'\s*DEF NUM_LANDMARKS', line):
            break
    return names


def map_labels(repo):
    """map constant -> scripts label (CamelCase), from data/maps/attributes.asm"""
    out = {}
    for m in re.finditer(r'^\s*map_attributes\s+(\w+),\s*(\w+)', read(repo, 'data/maps/attributes.asm'), re.M):
        out[m.group(2)] = m.group(1)
    return out


def map_info(repo):
    """CamelCase label -> (landmark, fish group), from data/maps/maps.asm"""
    out = {}
    for m in re.finditer(r'^\s*map\s+(\w+),\s*\w+,\s*\w+,\s*(\w+),.*?,\s*(FISHGROUP_\w+)\s*$', read(repo, 'data/maps/maps.asm'), re.M):
        out[m.group(1)] = (m.group(2), m.group(3))
    return out


def legendaries(repo):
    src = read(repo, 'engine/events/nuzlocke.asm')
    block = src.split('NuzlockeLegendaries:', 1)[1].split('dw -1', 1)[0]
    return set(re.findall(r'dw\s+(\w+)', block))


def wild_table_maps(repo):
    maps = set()
    for name in sorted(os.listdir(os.path.join(repo, 'data/wild'))):
        if not name.endswith('.asm') or name == os.path.basename(OUT):
            continue
        text = read(repo, 'data/wild/' + name)
        if name.startswith(('johto_', 'kanto_', 'hoenn_')):
            maps |= set(re.findall(r'^\s*def_(?:grass|water)_wildmons\s+(\w+)', text, re.M))
        elif name.startswith('swarm_'):
            maps |= set(re.findall(r'^\s*map_id\s+(\w+)', text, re.M))
        elif name == 'treemon_maps.asm':
            for m in re.finditer(r'^\s*treemon_map\s+(\w+),\s*(\w+)', text, re.M):
                if m.group(2) != 'TREEMON_SET_NONE':
                    maps.add(m.group(1))
    return maps


def script_maps(repo, legends):
    """CamelCase labels of maps whose scripts have a counted loadwildmon"""
    found = {}
    for root, _, files in os.walk(os.path.join(repo, 'maps')):
        for name in files:
            if not name.endswith('.asm'):
                continue
            lines = read(repo, os.path.relpath(os.path.join(root, name), repo)).splitlines()
            for i, line in enumerate(lines):
                m = re.match(r'\s*loadwildmon\s+(\w+)', line)
                if not m:
                    continue
                near = ' '.join(lines[max(0, i - 3):i + 4])
                if m.group(1) in legends or 'loadboss' in near or 'NUZLOCKE_FORCED' in near:
                    continue
                found.setdefault(name[:-4], []).append(m.group(1))
    return found


def build(repo):
    names = landmarks(repo)
    const_to_label = map_labels(repo)
    info = map_info(repo)
    legends = legendaries(repo)
    reasons = {}  # landmark -> set of reasons
    special = []

    def add(label, why):
        if label not in info:
            raise SystemExit(f'unknown map {label} ({why})')
        landmark = info[label][0]
        if landmark == 'LANDMARK_SPECIAL':
            special.append(f'{label} ({why})')
            return
        reasons.setdefault(landmark, set()).add(why)

    for const in sorted(wild_table_maps(repo)):
        add(const_to_label[const], 'wild')
    for label, (landmark, fish) in sorted(info.items()):
        if fish != 'FISHGROUP_NONE':
            add(label, 'fish')
    for label, species in sorted(script_maps(repo, legends).items()):
        add(label, 'script ' + '/'.join(species))

    bits = [0] * ((len(names) + 7) // 8)
    for landmark in reasons:
        i = names.index(landmark)
        bits[i // 8] |= 1 << (i % 8)
    lines = [
        '; Generated by tools/nuzlocke_area_table.py: do not edit.',
        '; One bit per landmark (LANDMARK_* order, bit 0 first): set when the',
        "; landmark has a wild Pokémon whose catch uses the Nuzlocke area.",
        '',
        'NuzlockeEncounterLandmarks:',
    ]
    for b in range(len(bits)):
        group = [n[len('LANDMARK_'):] for n in names[b * 8:b * 8 + 8] if n in reasons]
        lines.append(f'\tdb %{bits[b]:08b} ; ' + (', '.join(group) if group else '-'))
    lines.append('\tassert @ - NuzlockeEncounterLandmarks == (NUM_LANDMARKS + 7) / 8')
    return '\n'.join(lines) + '\n', reasons, special, names


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    repo = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    text, reasons, special, names = build(repo)
    path = os.path.join(repo, OUT)
    if '--check' in sys.argv:
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if old != text:
            print(f'{OUT} is out of date: run tools/nuzlocke_area_table.py')
            sys.exit(1)
        print(f'{OUT} is up to date')
        return
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'{len(reasons)} of {len(names) - 1} landmarks have catches; wrote {OUT}')
    for s in special:
        print('  LANDMARK_SPECIAL map, not listed:', s)


if __name__ == '__main__':
    main()
