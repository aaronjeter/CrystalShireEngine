#!/usr/bin/env python3
"""Generate data/trainers/scaled_evolutions.asm: the evolutions a scaled trainer
party (party option SCALED) applies to its Pokemon by level.

    python3 tools/scaled_evos_table.py [REPO] [--check]

Each row is (species, level, evolution): a scaled trainer's Pokemon evolves
along the rows whose level its own level reaches, as far as it can (a branch is
picked by the trainer ID and party slot; engine/battle/scaled_trainers.asm).

- EVOLVE_LEVEL and EVOLVE_STAT rows keep their level.
- EVOLVE_ITEM and EVOLVE_HAPPINESS rows get a fallback level by the species'
  stage (STAGE_LEVELS), or FALLBACK_OVERRIDES.
- Only evolutions to the next stage of the same family count: form swaps
  (Vulpix -> Alolan Vulpix, Ninetales -> Ninetales2, ...) and Mega Stones
  (MEGA_ITEM) are left out.

--check exits with 1 if the file is out of date.
"""
import os
import re
import sys

OUT = 'data/trainers/scaled_evolutions.asm'
EVOS_FILES = ['kanto', 'johto', 'hoenn', 'alt', 'mega']
MEGA_ITEM = re.compile(r'ITE_[XY]$')
# fallback level for item and happiness evolutions, by the stage evolving
# (0: a first stage, 1: its evolution, ...)
ITEM_LEVELS = [30, 36, 42]
HAPPINESS_LEVELS = [15, 36, 42]
FALLBACK_OVERRIDES = {('CHANSEY', 'BLISSEY'): 40}


def read(repo, path):
    with open(os.path.join(repo, path), encoding='utf-8') as f:
        return f.read()


def species(repo):
    names = []
    for line in read(repo, 'constants/pokemon_constants.asm').splitlines():
        if 'DEF NUM_POKEMON' in line:
            break
        m = re.match(r'\s*const\s+(\w+)', line)
        if m:
            names.append(m.group(1))
    return names


def evolutions(repo, names):
    """{species: [(method, param, target)]}"""
    labels, blocks = [], {}
    for f in EVOS_FILES:
        text = read(repo, f'data/pokemon/evos_attacks_{f}.asm')
        table = text.split('::', 1)[1]
        table = re.split(r'^\w+EvosAttacks:', table, maxsplit=1, flags=re.M)[0]
        labels += re.findall(r'^\s*dw\s+(\w+)', table, re.M)
        for m in re.finditer(r'^(\w+EvosAttacks):\s*\n(.*?)^\s*db 0', text, re.M | re.S):
            rows = []
            for line in m.group(2).splitlines():
                code = line.split(';', 1)[0].strip()
                e = re.match(r'(dbbw|dbww|dbbbw)\s+(EVOLVE_\w+),\s*(.*)', code)
                if e:
                    args = [a.strip() for a in e.group(3).split(',')]
                    rows.append((e.group(2), args[0], args[-1]))
            blocks[m.group(1)] = rows
    assert len(labels) == len(names), (len(labels), len(names))
    return {names[i]: blocks.get(lab, []) for i, lab in enumerate(labels)}


def build(repo):
    names = species(repo)
    firsts = re.findall(r'^\s*dw\s+(\w+)', read(repo, 'data/pokemon/first_stages.asm'), re.M)
    assert len(firsts) == len(names), (len(firsts), len(names))
    first = dict(zip(names, firsts))
    evos = evolutions(repo, names)

    # stage depth: the shortest path from the species' first stage within its family
    depth = {}
    for s in names:
        if first[s] == s:
            depth[s] = 0
    changed = True
    while changed:
        changed = False
        for s in names:
            if s not in depth:
                continue
            for _, _, t in evos[s]:
                if t in first and first[t] == first[s] and t not in depth:
                    depth[t] = depth[s] + 1
                    changed = True

    rows = []
    for s in names:
        if s not in depth:
            continue
        for method, param, t in evos[s]:
            if t not in first or first[t] != first[s] or depth.get(t) != depth[s] + 1:
                continue  # a form swap, or another family
            if method in ('EVOLVE_LEVEL', 'EVOLVE_STAT'):
                level = int(param)
            elif method == 'EVOLVE_ITEM':
                if MEGA_ITEM.search(param):
                    continue
                level = ITEM_LEVELS[min(depth[s], len(ITEM_LEVELS) - 1)]
            elif method == 'EVOLVE_HAPPINESS':
                level = HAPPINESS_LEVELS[min(depth[s], len(HAPPINESS_LEVELS) - 1)]
            else:
                raise ValueError(f'{s}: unknown method {method}')
            level = FALLBACK_OVERRIDES.get((s, t), level)
            same = [i for i, r in enumerate(rows) if r[0] == s and r[2] == t]
            if same:  # two ways to the same evolution: keep the lower level
                if level < rows[same[0]][1]:
                    rows[same[0]] = (s, level, t, method, param)
                continue
            rows.append((s, level, t, method, param))

    lines = [
        '; Generated by tools/scaled_evos_table.py: do not edit.',
        '; A scaled trainer\'s Pokemon evolves along these rows as far as its level',
        '; allows (engine/battle/scaled_trainers.asm). Item and happiness evolutions',
        '; use a fallback level by stage; form swaps and Mega Stones are left out.',
        '',
        'MACRO scaled_evo',
        '; species, level, evolution',
        '\tdw \\1',
        '\tdb \\2',
        '\tdw \\3',
        'ENDM',
        '',
        'ScaledTrainerEvolutions:',
    ]
    for s, level, t, method, param in rows:
        note = '' if method == 'EVOLVE_LEVEL' else f' ; {method[7:].lower()} {param}'
        lines.append(f'\tscaled_evo {s}, {level}, {t}{note}')
    lines.append('.End:')
    return '\n'.join(lines) + '\n', len(rows)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    repo = args[0] if args else '.'
    text, n = build(repo)
    path = os.path.join(repo, OUT)
    if '--check' in sys.argv:
        current = read(repo, OUT) if os.path.exists(path) else ''
        if current != text:
            print(f'{OUT} is out of date: run tools/scaled_evos_table.py')
            sys.exit(1)
        print(f'{OUT} is up to date ({n} evolutions)')
        return
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote {OUT}: {n} evolutions')


if __name__ == '__main__':
    main()
