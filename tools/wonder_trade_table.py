#!/usr/bin/env python3
"""Generate data/events/wonder_trade_pool.asm: the Wonder Trade's species pool
(every species that is its own first stage, minus EXCLUDED) and the level
evolutions reachable from it.

    python3 tools/wonder_trade_table.py [REPO] [--check]

The pool reads data/pokemon/first_stages.asm (FirstEvoStages) against the
species constants; the evolutions read the EVOLVE_LEVEL lines of
data/pokemon/evos_attacks_*.asm, in EvosAttacksPointers order. --check exits
with 1 if the file is out of date.
"""
import os, re, sys

OUT = 'data/events/wonder_trade_pool.asm'
# Legendaries and mythicals (as NuzlockeLegendaries), the Golden Sun Djinn and
# event-only species.
EXCLUDED = [
    'ARTICUNO', 'ZAPDOS', 'MOLTRES', 'MEWTWO', 'MEW',
    'RAIKOU', 'ENTEI', 'SUICUNE', 'LUGIA', 'HO_OH', 'CELEBI',
    'REGIROCK', 'REGICE', 'REGISTEEL', 'LATIAS', 'LATIOS', 'KYOGRE', 'GROUDON', 'RAYQUAZA', 'JIRACHI',
    'MERCURY', 'VENUS', 'MARS', 'JUPITER',
    'IRONBUNDLE',
]
EVOS_FILES = ['kanto', 'johto', 'hoenn', 'alt', 'mega']


def read(repo, path):
    with open(os.path.join(repo, path), encoding='utf-8') as f:
        return f.read()


def species(repo):
    names = []
    for line in read(repo, 'constants/pokemon_constants.asm').splitlines():
        if 'DEF NUM_POKEMON' in line:
            break
        m = re.match(r'\s*const\s+(\w+)', line)
        if m:
            names.append(m.group(1))
    return names


def level_evos(repo):
    """{species constant: [(level, evolved species)]} for EVOLVE_LEVEL entries"""
    labels, blocks = [], {}
    for f in EVOS_FILES:
        text = read(repo, f'data/pokemon/evos_attacks_{f}.asm')
        table = text.split('::', 1)[1]
        table = re.split(r'^\w+EvosAttacks:', table, maxsplit=1, flags=re.M)[0]
        labels += re.findall(r'^\s*dw\s+(\w+)', table, re.M)
        for m in re.finditer(r'^(\w+EvosAttacks):\s*\n(.*?)^\s*db 0', text, re.M | re.S):
            blocks[m.group(1)] = re.findall(r'^\s*dbbw\s+EVOLVE_LEVEL,\s*(\d+),\s*(\w+)', m.group(2), re.M)
    return labels, blocks


def build(repo):
    names = species(repo)
    firsts = re.findall(r'^\s*dw\s+(\w+)', read(repo, 'data/pokemon/first_stages.asm'), re.M)
    assert len(firsts) == len(names), (len(firsts), len(names))
    for e in EXCLUDED:
        assert e in names, e
    pool = [n for n, f in zip(names, firsts) if n == f and n not in EXCLUDED]
    assert len(pool) < 256, 'WonderTradeDrawSpecies draws with RandomRange (below 256)'
    labels, blocks = level_evos(repo)
    assert len(labels) == len(names), (len(labels), len(names))
    evos = {names[i]: [(int(l), s) for l, s in blocks.get(lab, [])] for i, lab in enumerate(labels)}
    # level evolutions reachable from the pool
    rows, todo, seen = [], list(pool), set()
    while todo:
        s = todo.pop(0)
        if s in seen:
            continue
        seen.add(s)
        for lvl, to in evos.get(s, []):
            rows.append((s, lvl, to))
            todo.append(to)
    lines = [
        '; Generated by tools/wonder_trade_table.py: do not edit.',
        '',
        'WonderTradePool:',
        '; species that are their own first stage, without legendaries, mythicals,',
        '; the Djinn and event-only species',
        f'\tdw {len(pool)}',
    ]
    for i in range(0, len(pool), 6):
        lines.append('\tdw ' + ', '.join(pool[i:i + 6]))
    lines += [
        '',
        'WonderTradeLevelEvos:',
        '; level evolutions reachable from the pool: species, level, evolved species',
    ]
    for s, lvl, to in rows:
        lines.append(f'\tdw {s}\n\tdb {lvl}\n\tdw {to}')
    lines.append('\tdw 0 ; end')
    return '\n'.join(lines) + '\n', pool, rows


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    repo = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    text, pool, rows = build(repo)
    path = os.path.join(repo, OUT)
    if '--check' in sys.argv:
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if old != text:
            print(f'{OUT} is out of date: run tools/wonder_trade_table.py')
            sys.exit(1)
        print(f'{OUT} is up to date')
        return
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'{len(pool)} species in the pool, {len(rows)} level evolutions; wrote {OUT}')


if __name__ == '__main__':
    main()
